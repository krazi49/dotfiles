#!/usr/bin/env node
/**
 * oganesson — dotfiles design token builder
 *
 * Reads:
 *   - brand/appearance.json   (non-color settings: fonts, borders, radius, spacing, motion)
 *   - ~/.config/waybar/theme.css  (matugen-generated colors)
 *
 * Emits:
 *   - brand/dist/tokens.json       (frozen snapshot)
 *   - brand/dist/preview.html      (visual palette preview)
 *   - ~/.config/waybar/theme.css   (re-written with appearance vars appended)
 *   - ~/.config/gtk-3.0/settings.ini  (font, theme)
 *
 * Matugen handles its own templates. This fills in whatever matugen doesn't touch.
 */

const fs = require('fs');
const path = require('path');

const DOTFILES = path.join(__dirname);
const DIST = path.join(DOTFILES, '.brand', 'dist');
fs.mkdirSync(DIST, { recursive: true });

// ── Load inputs ─────────────────────────────────────────────
const appearance = JSON.parse(fs.readFileSync(path.join(DOTFILES, 'appearance.json'), 'utf8'));

// All dotfiles dirs are symlinked to ~/.config/*, so resolving against DOTFILES is the same
// All dotfiles dirs are symlinked to ~/.config/*, so DOTFILES == live
const THEME_PATH = path.join(DOTFILES, 'waybar', 'theme.css');
const THEME_LIGHT_PATH = process.env.MATUGEN_THEME_LIGHT || path.join(DOTFILES, 'waybar', 'theme-light.css');

function parseDefineColorCSS(filepath) {
  if (!fs.existsSync(filepath)) return null;
  const src = fs.readFileSync(filepath, 'utf8');
  const colors = {};
  const re = /@define-color\s+(\S+)\s+(#[0-9a-fA-F]+);/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    colors[m[1]] = m[2].toLowerCase();
  }
  return colors;
}

const dark = parseDefineColorCSS(THEME_PATH);
const light = parseDefineColorCSS(THEME_LIGHT_PATH);

if (!dark) {
  console.error(`can't find ${THEME_PATH} — run matugen first`);
  process.exit(1);
}

// ── Merged tokens.json ──────────────────────────────────────
const tokens = {
  name: 'oganesson',
  version: appearance.version,
  source_color: dark.source_color || 'unknown',
  generated: new Date().toISOString(),
  color: dark,
  light: light ? { color: light } : undefined,
  typography: appearance.typography,
  shape: appearance.shape,
  border: appearance.border,
  spacing: appearance.spacing,
  motion: appearance.motion,
  window: appearance.window,
  notification: appearance.notification,
};

fs.writeFileSync(path.join(DIST, 'tokens.json'), JSON.stringify(tokens, null, 2));
console.log('  \u2713 dist/tokens.json');

// ── Waybar theme.css (append appearance variables) ──────────
// Matugen already wrote the color portion. We append :root vars after it.
function waybarVarsCSS(a) {
  const T = a.typography;
  const S = a.shape;
  const B = a.border;
  const SP = a.spacing;
  const M = a.motion;

  return `
/* ── appearance (generated by brand/build.js) ── */
:root {
  /* typography */
  --font-sans: "${T.sans.family}";
  --font-mono: "${T.mono.family}";
  --font-display: "${T.display.family}";
  --font-alt: "${T.alt.family}";
  --font-size-ui: ${T.sans.size_ui}px;
  --font-size-body: ${T.sans.size_body}px;
  --font-size-sm: ${T.sans.size_sm}px;
  --font-size-xs: ${T.sans.size_xs}px;
  --font-size-2xs: ${T.sans.size_2xs}px;
  --font-size-mono-base: ${T.mono.size_base}px;
  --mono-family: "${T.mono.family}";

  /* shape */
  --corner-radius: ${S.corner_radius}px;

  /* border */
  --border-width-thick: ${B.width_thick}px;
  --border-width-medium: ${B.width_medium}px;
  --border-width-thin: ${B.width_thin}px;
  --border-width-hairline: ${B.width_hairline}px;
  --border-style: ${B.style};

  /* spacing */
  --space-px: 1px;
  --space-0: 0;
  --space-1: ${SP["1"]}px;
  --space-2: ${SP["2"]}px;
  --space-3: ${SP["3"]}px;
  --space-4: ${SP["4"]}px;
  --space-5: ${SP["5"]}px;
  --space-6: ${SP["6"]}px;
  --space-8: ${SP["8"]}px;
  --space-10: ${SP["10"]}px;
  --space-12: ${SP["12"]}px;
  --space-16: ${SP["16"]}px;
  --space-20: ${SP["20"]}px;
  --space-24: ${SP["24"]}px;

  /* motion */
  --duration-fast: ${M.duration_fast}ms;
  --duration-normal: ${M.duration_normal}ms;
  --duration-moderate: ${M.duration_moderate}ms;
  --duration-slow: ${M.duration_slow}ms;
  --easing-standard: ${M.easing_standard};
}
`;
}

const existingCSS = fs.readFileSync(THEME_PATH, 'utf8');
// Only append if not already there
if (!existingCSS.includes('/* ── appearance')) {
  fs.writeFileSync(THEME_PATH, existingCSS.trimEnd() + '\n' + waybarVarsCSS(appearance));
  console.log('  \u2713 ~/.config/waybar/theme.css (appended appearance vars)');
} else {
  console.log('  \u2713 ~/.config/waybar/theme.css (appearance vars already present, skipped)');
}

// ── GTK settings.ini ────────────────────────────────────────
const GTK_SETTINGS = path.join(DOTFILES, 'gtk-3.0', 'settings.ini');
const gtkContent = `[Settings]
gtk-theme-name=adw-gtk3-dark
gtk-font-name=${appearance.typography.sans.family} ${appearance.typography.sans.size_ui}
`;
fs.writeFileSync(GTK_SETTINGS, gtkContent);
console.log('  \u2713 ~/.config/gtk-3.0/settings.ini');

// Also write gtk-4.0 version
const GTK4_SETTINGS = path.join(DOTFILES, 'gtk-4.0', 'settings.ini');
fs.writeFileSync(GTK4_SETTINGS, gtkContent);
console.log('  \u2713 ~/.config/gtk-4.0/settings.ini');

// ── Preview HTML ────────────────────────────────────────────
const swatches = Object.entries(dark)
  .filter(([k]) => !['source_color', 'scrim', 'shadow'].includes(k) && !k.startsWith('inverse_') && !k.startsWith('on_'))
  .slice(0, 30);

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>oganesson — palette preview</title>
<style>
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { background: ${dark.surface}; color: ${dark.on_surface}; font-family: ${appearance.typography.sans.family}, system-ui, sans-serif; padding: 2rem; }
  h1 { font-size: 1.5rem; margin-bottom: 0.25rem; font-weight: 700; }
  .seed { font-size: 0.875rem; color: ${dark.on_surface_variant}; margin-bottom: 1rem; }
  .meta { font-size: 0.75rem; color: ${dark.outline}; margin-bottom: 2rem; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(200px, 1fr)); gap: 1rem; }
  .swatch { border-radius: ${appearance.shape.corner_radius}px; overflow: hidden; border: ${appearance.border.width_thin}px solid ${dark.outline}; }
  .swatch-bar { height: 80px; display: flex; align-items: flex-end; padding: 8px; }
  .swatch-bar span { font-size: 0.75rem; font-weight: 600; background: rgba(0,0,0,0.5); padding: 2px 6px; border-radius: 2px; color: white; }
  .swatch-label { padding: 6px 8px; font-size: 0.75rem; background: ${dark.surface_container}; }
  .swatch-label .name { font-weight: 600; }
  .swatch-label .hex { color: ${dark.on_surface_variant}; }

  .group { border: ${appearance.border.width_hairline}px solid ${dark.outline_variant}; padding: 1.5rem; margin-top: 1.5rem; }
  .group h2 { font-size: 1rem; margin-bottom: 0.75rem; font-weight: 600; color: ${dark.primary}; }
  .font-demo { display: flex; flex-direction: column; gap: 0.25rem; }
  .font-demo .sans { font-family: "${appearance.typography.sans.family}"; font-size: 16px; }
  .font-demo .mono { font-family: "${appearance.typography.mono.family}"; font-size: 14px; }
  .font-demo .display { font-family: "${appearance.typography.display.family}"; font-size: 24px; font-weight: 700; }
  .font-demo .alt { font-family: "${appearance.typography.alt.family}"; font-size: 14px; }
  .info-grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(200px, 1fr)); gap: 0.5rem; font-size: 0.8125rem; }
  .info-grid .label { color: ${dark.on_surface_variant}; }
</style>
</head>
<body>
<h1>oganesson</h1>
<p class="seed">seed: ${dark.source_color} \u00b7 ${Object.keys(dark).length} color tokens</p>
<p class="meta">${appearance.typography.sans.family} \u00b7 ${appearance.typography.mono.family} \u00b7 radius ${appearance.shape.corner_radius}px \u00b7 border ${appearance.border.width_thick}px</p>

<div class="group">
  <h2>colors</h2>
  <div class="grid">
${swatches.map(s => {
  const textColor = dark[`on_${s[0]}`] || dark.on_surface;
  return `    <div class="swatch">
      <div class="swatch-bar" style="background:${s[1]};color:${textColor}"><span>${s[1]}</span></div>
      <div class="swatch-label"><div class="name">${s[0]}</div><div class="hex">on: ${textColor}</div></div>
    </div>`;
}).join('\n')}
  </div>
</div>

<div class="group">
  <h2>fonts</h2>
  <div class="font-demo">
    <div class="display">display \u2014 ${appearance.typography.display.family}</div>
    <div class="sans">sans \u2014 ${appearance.typography.sans.family} (${appearance.typography.sans.size_ui}px ui / ${appearance.typography.sans.size_body}px body)</div>
    <div class="alt">alt \u2014 ${appearance.typography.alt.family}</div>
    <div class="mono">mono \u2014 ${appearance.typography.mono.family} (${appearance.typography.mono.size_base}px base)</div>
  </div>
</div>

<div class="group">
  <h2>appearance</h2>
  <div class="info-grid">
    <div><span class="label">corner radius</span><br>${appearance.shape.corner_radius}px</div>
    <div><span class="label">border thick</span><br>${appearance.border.width_thick}px</div>
    <div><span class="label">border medium</span><br>${appearance.border.width_medium}px</div>
    <div><span class="label">border thin</span><br>${appearance.border.width_thin}px</div>
    <div><span class="label">window padding</span><br>${appearance.window.padding}px</div>
    <div><span class="label">notif timeout</span><br>${appearance.notification.timeout}s</div>
    <div><span class="label">notif width</span><br>${appearance.notification.width}px</div>
    <div><span class="label">duration fast</span><br>${appearance.motion.duration_fast}ms</div>
  </div>
</div>

</body>
</html>`;

fs.writeFileSync(path.join(DIST, 'preview.html'), html);
console.log('  \u2713 dist/preview.html');

console.log(`\n\u2728 build complete \u2014 ${appearance.typography.sans.family} / ${appearance.typography.mono.family} / r${appearance.shape.corner_radius}`);
